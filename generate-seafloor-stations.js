function parseRows(source) {
  const seen = new Set();
  return source.split(/\r?\n/).map((line, index) => {
    const [network, officialCode, latText, lngText, depthText] = line.split('|');
    const lat = Number(latText);
    const lng = Number(lngText);
    const depth = Number(depthText);
    if (!['DONET1', 'DONET2', 'S-net', 'N-net'].includes(network)) {
      throw new Error(`Invalid network on row ${index + 1}: ${network}`);
    }
    if (!/^[MN]\.[A-Z0-9]+$/.test(officialCode) || seen.has(officialCode)) {
      throw new Error(`Invalid or duplicate official code on row ${index + 1}: ${officialCode}`);
    }
    if (!Number.isFinite(lat) || !Number.isFinite(lng) || !Number.isInteger(depth) || depth <= 0) {
      throw new Error(`Invalid station measurements on row ${index + 1}`);
    }
    seen.add(officialCode);
    return {
      name: officialCode,
      officialCode,
      lat,
      lng,
      type: 'seafloor',
      depth,
      network,
      catalogStatus: 'listed',
      operationalStatus: 'not-provided',
      sourceUrl: SOURCE_URL,
      sourceRetrieved: SOURCE_RETRIEVED,
    };
  });
}

const stations = parseRows(OFFICIAL_ROWS);
const counts = stations.reduce((result, station) => {
  result[station.network] = (result[station.network] || 0) + 1;
  return result;
}, {});

